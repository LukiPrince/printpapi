// Writes src/types.ts from crates/server/openapi.json. No dependency: the document is the one
// description of the wire format, so the types are generated from it and a test fails when the
// committed file differs (test/types.test.ts). Supported keywords are the subset the document uses;
// anything else throws, so a new keyword cannot slip past the types unnoticed.
import { readFileSync, writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";

const KEYWORDS = new Set([
  "$ref", "type", "properties", "required", "items", "enum", "oneOf", "additionalProperties",
  "minimum", "maximum", "minLength", "maxLength", "description", "title", "default",
]);

const ident = (k) => (/^[A-Za-z_$][\w$]*$/.test(k) ? k : JSON.stringify(k));

function doc(text, indent) {
  if (!text) return "";
  const body = text.replace(/\*\//g, "*\\/").split("\n").map((l) => l.trimEnd());
  return body.length === 1
    ? indent + "/** " + body[0] + " */\n"
    : indent + "/**\n" + body.map((l) => indent + " * " + l).join("\n") + "\n" + indent + " */\n";
}

function ts(s, depth, at) {
  for (const k of Object.keys(s)) {
    if (!KEYWORDS.has(k)) throw new Error(at + ": unsupported schema keyword " + k);
  }
  if (s.$ref) return s.$ref.replace("#/components/schemas/", "");
  if (s.oneOf) return s.oneOf.map((c) => ts(c, depth, at)).join(" | ");
  if (s.enum) return s.enum.map((v) => JSON.stringify(v)).join(" | ");
  if (s.type === undefined) return "unknown";
  const types = Array.isArray(s.type) ? s.type : [s.type];
  return types.map((t) => one(t, s, depth, at)).join(" | ");
}

function one(t, s, depth, at) {
  switch (t) {
    case "string": return "string";
    case "integer": case "number": return "number";
    case "boolean": return "boolean";
    case "null": return "null";
    case "array": {
      const item = ts(s.items ?? {}, depth, at);
      return item.includes(" | ") ? "Array<" + item + ">" : item + "[]";
    }
    case "object": return object(s, depth, at);
    default: throw new Error(at + ": unsupported type " + t);
  }
}

function object(s, depth, at) {
  const props = s.properties;
  if (!props) {
    return s.additionalProperties && typeof s.additionalProperties === "object"
      ? "{ [key: string]: " + ts(s.additionalProperties, depth, at) + " }"
      : "object"; // not Record<string, unknown>: an interface is no index signature, and a free-form object is any object
  }
  const pad = "  ".repeat(depth + 1);
  const required = new Set(s.required ?? []);
  let out = "{\n";
  for (const [k, v] of Object.entries(props)) {
    out += doc(v.description, pad);
    out += pad + ident(k) + (required.has(k) ? "" : "?") + ": " + ts(v, depth + 1, at + "." + k) + ";\n";
  }
  return out + "  ".repeat(depth) + "}";
}

/** The text of src/types.ts for an OpenAPI document. */
export function generate(openapi) {
  let out =
    "// Generated by scripts/gen-types.mjs from crates/server/openapi.json. Do not edit by hand:\n" +
    "// change the document, then run \"npm run gen-types\". test/types.test.ts fails on drift.\n\n";
  for (const [name, s] of Object.entries(openapi.components.schemas)) {
    out += doc(s.description, "");
    const body = ts(s, 0, name);
    out += s.type === "object" && s.properties
      ? "export interface " + name + " " + body + "\n\n"
      : "export type " + name + " = " + body + ";\n\n";
  }
  return out.trimEnd() + "\n";
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const root = new URL("../../../crates/server/openapi.json", import.meta.url);
  const target = new URL("../src/types.ts", import.meta.url);
  writeFileSync(target, generate(JSON.parse(readFileSync(root, "utf8"))));
  console.log("wrote src/types.ts");
}
